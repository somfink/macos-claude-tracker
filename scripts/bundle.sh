#!/usr/bin/env bash
# Builds a release binary and wraps it in dist/Claude Tracker.app, with the desktop widget
# extension in Contents/PlugIns when a development identity is available.
# Usage: scripts/bundle.sh [--install]   --install also copies the app to ~/Applications.
#
# Signing: uses the first "Apple Development" identity in the keychain, so macOS keeps the
# Accessibility permission across rebuilds (an ad-hoc signature changes every build and
# silently invalidates it). Override with SIGN_IDENTITY="..." or SIGN_IDENTITY=- for ad-hoc.
#
# Widget: WidgetKit extensions must be sandboxed and get their data through an App Group,
# whose id must start with the signing Team ID. The Team ID is read from the certificate;
# with ad-hoc signing there is none, so the widget is skipped.
set -euo pipefail

detect_identity() {
    security find-identity -v -p codesigning 2>/dev/null \
        | sed -n 's/.*"\(Apple Development: [^"]*\)".*/\1/p' \
        | head -1
}

team_id_of() {
    security find-certificate -c "$1" -p 2>/dev/null \
        | openssl x509 -noout -subject 2>/dev/null \
        | sed -n 's/.*OU *= *\([A-Z0-9]\{10\}\).*/\1/p'
}

SIGN_IDENTITY="${SIGN_IDENTITY:-$(detect_identity)}"
SIGN_IDENTITY="${SIGN_IDENTITY:--}"
TEAM_ID=""
[[ "$SIGN_IDENTITY" != "-" ]] && TEAM_ID="$(team_id_of "$SIGN_IDENTITY")"
APP_GROUP="${TEAM_ID:+$TEAM_ID.dev.claude-tracker}"

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
APP_NAME="Claude Tracker"
EXECUTABLE="ClaudeTracker"
WIDGET_NAME="ClaudeTrackerWidget"
APP_DIR="$ROOT/dist/$APP_NAME.app"
WIDGET_DIR="$APP_DIR/Contents/PlugIns/$WIDGET_NAME.appex"
WORK_DIR="$ROOT/.build/bundle"
INSTALL_DIR="$HOME/Applications"
MIN_MACOS="14.0"

# Copies a plist/entitlements template, filling in the App Group id.
render() {
    sed "s/__APP_GROUP__/${APP_GROUP:-__APP_GROUP__}/g" "$1" > "$2"
}

build_widget() {
    local sdk
    sdk="$(xcrun --show-sdk-path --sdk macosx)"
    mkdir -p "$WIDGET_DIR/Contents/MacOS"
    # Core sources are compiled into the extension module: SwiftPM cannot build app
    # extensions, and the widget needs only a few pure types from TrackerCore.
    # The entry point is what Xcode sets for every app extension (LD_ENTRY_POINT): started
    # from a plain `main`, the extension exits right after launch and the gallery stays empty.
    xcrun swiftc -O -swift-version 6 -parse-as-library -application-extension \
        -module-name "$WIDGET_NAME" \
        -sdk "$sdk" -target "$(uname -m)-apple-macos$MIN_MACOS" \
        -framework WidgetKit -framework SwiftUI -framework Foundation \
        -Xlinker -e -Xlinker _NSExtensionMain \
        "$ROOT"/Sources/TrackerCore/*.swift "$ROOT"/Widget/*.swift \
        -o "$WIDGET_DIR/Contents/MacOS/$WIDGET_NAME"
    render "$ROOT/Widget/Info.plist" "$WIDGET_DIR/Contents/Info.plist"
    render "$ROOT/Widget/Widget.entitlements" "$WORK_DIR/Widget.entitlements"
    codesign --force --sign "$SIGN_IDENTITY" --entitlements "$WORK_DIR/Widget.entitlements" "$WIDGET_DIR"
}

cd "$ROOT"
swift build -c release --product "$EXECUTABLE"
BIN_DIR="$(swift build -c release --show-bin-path)"

rm -rf "$APP_DIR"
mkdir -p "$APP_DIR/Contents/MacOS" "$APP_DIR/Contents/Resources" "$WORK_DIR"
cp "$BIN_DIR/$EXECUTABLE" "$APP_DIR/Contents/MacOS/$EXECUTABLE"
render "$ROOT/Resources/Info.plist" "$APP_DIR/Contents/Info.plist"
# Generated by scripts/make-icon.sh; shown on notification banners, in Finder and Spotlight.
cp "$ROOT/Resources/AppIcon.icns" "$APP_DIR/Contents/Resources/AppIcon.icns"

if [[ -n "$APP_GROUP" ]]; then
    build_widget
    render "$ROOT/Resources/ClaudeTracker.entitlements" "$WORK_DIR/ClaudeTracker.entitlements"
    # Inner bundles first: signing the app seals the already-signed extension.
    codesign --force --sign "$SIGN_IDENTITY" --entitlements "$WORK_DIR/ClaudeTracker.entitlements" "$APP_DIR"
    echo "Widget: $WIDGET_DIR (app group $APP_GROUP)"
else
    codesign --force --sign "$SIGN_IDENTITY" "$APP_DIR"
    echo "Widget: skipped (no Team ID; ad-hoc signing)"
fi

echo "Built: $APP_DIR (signed: $SIGN_IDENTITY)"

if [[ "${1:-}" == "--install" ]]; then
    mkdir -p "$INSTALL_DIR"
    rm -rf "$INSTALL_DIR/$APP_NAME.app"
    cp -R "$APP_DIR" "$INSTALL_DIR/"
    # Two LaunchServices claims for one bundle id (dist/ and the installed copy) keep the
    # widget out of the desktop gallery, so only the installed copy stays registered.
    LSREGISTER=/System/Library/Frameworks/CoreServices.framework/Frameworks/LaunchServices.framework/Support/lsregister
    "$LSREGISTER" -u "$APP_DIR" || echo "warning: could not unregister $APP_DIR" >&2
    "$LSREGISTER" -f "$INSTALL_DIR/$APP_NAME.app" || echo "warning: could not register the installed app" >&2
    echo "Installed: $INSTALL_DIR/$APP_NAME.app"
fi
